/**
 * RFC 4122's URL namespace, `uuid.NAMESPACE_URL`.
 *
 * A literal rather than a derivation: CPython writes it as a literal too, and
 * there is nothing to derive it *from* -- it is one of the four constants the
 * RFC assigns.
 */
export const NAMESPACE_URL = "6ba7b811-9dad-11d1-80b4-00c04fd430c8";

/**
 * The name interlock hashes under {@link NAMESPACE_URL} to get its own
 * namespace. Exported separately from the namespace it produces so a reader can
 * see that the constant below is *computed*, byte for byte, the way the source
 * computes it -- rather than transcribed as a literal that would then have to
 * be trusted.
 */
export const SESSION_UUID_NAMESPACE_NAME =
  "https://github.com/suisya-systems/interlock/session-uuid";

/**
 * Namespace for deriving a `claude`-acceptable session UUID from an S1 id.
 *
 * Fixed, so the derivation is a pure function of the id alone. Computed at
 * module load exactly as `claude_cli_provider.py` computes it at import.
 */
export const SESSION_UUID_NAMESPACE: string = uuid5(NAMESPACE_URL, SESSION_UUID_NAMESPACE_NAME);

// --------------------------------------------------------------------------
// The two public functions
// --------------------------------------------------------------------------

/**
 * The `--session-id` value for one S1 session id, as a pure function.
 *
 * An id that already parses as a UUID -- in any spelling Python accepts -- is
 * honoured verbatim, canonicalised; anything else is mapped through
 * {@link SESSION_UUID_NAMESPACE}.
 *
 * The `typeof` guard has no counterpart in the source and is not a
 * generalisation: a non-`str` id already fails in Python, just less tidily --
 * `uuid.UUID(1)` raises `AttributeError: 'int' object has no attribute
 * 'replace'` and `uuid.UUID(None)` raises `TypeError`, measured on 3.12.3.
 * `claude_session_uuid` catches only `ValueError`, so both propagate out of it.
 * In TypeScript the parameter's declared type does not exclude
 * the value at runtime (rule 9), and the specific hazard is a boxed `String`
 * or any object with a `toString`: without the guard it would be coerced by
 * `replaceAll` and friends, and a `Symbol.toPrimitive` that answers differently
 * on successive reads would make this function impure -- which is the one
 * property it exists to have.
 */
export function claudeSessionUuid(sessionId: string): string {
  requireString(sessionId, "session id");
  return parsePythonUuid(sessionId) ?? uuid5(SESSION_UUID_NAMESPACE, sessionId);
}

/**
 * `str(uuid.UUID(text))`, or `undefined` where CPython raises `ValueError`.
 *
 * `undefined` rather than a thrown error because the source's control flow is
 * `try/except ValueError` around exactly this call, and a caller of this
 * function is always asking a question ("is this already a UUID?"), never
 * reporting a fault.
 *
 * CPython's parse, transcribed (`Lib/uuid.py`, `UUID.__init__`):
 *
 * ```python
 * hex = hex.replace('urn:', '').replace('uuid:', '')
 * hex = hex.strip('{}').replace('-', '')
 * if len(hex) != 32:
 *     raise ValueError('badly formed hexadecimal UUID string')
 * int = int_(hex, 16)
 * ```
 *
 * Four consequences that a hand-written `/^[0-9a-f]{8}-.../` check does not
 * have, all of them measured on 3.12.3 and all of them reachable from a
 * caller-chosen session id:
 *
 * - `'urn:'` and `'uuid:'` are removed **wherever they occur**, not just as a
 *   prefix, and only in that lowercase spelling: `URN:UUID:...` is refused.
 * - `strip('{}')` removes **any run** of `{` or `}` from either end, in any
 *   combination -- `}...{` parses, and so does `{{...}}`.
 * - Every `-` is removed, wherever it sits, so `1-2-3-...-f` parses. A leading
 *   `-` is removed too, which is why the sign this module's integer parse
 *   accepts is only `+`: a `-` can never survive to reach it.
 * - The remainder must be 32 characters **and a Python base-16 integer
 *   literal** -- which is a wider language than "32 hex digits". See
 *   {@link pythonHexIntegerLiteral}.
 *
 * The length is counted in **code points**, as Python's `len` counts it, not in
 * UTF-16 code units. The two differ for astral characters, and astral decimal
 * digits exist (`U+1D7CE` and its neighbours are `Nd`), so this is not an
 * academic distinction: a 32-code-point run of mathematical bold digits is a
 * string CPython parses and `text.length` would measure as 64.
 */
export function parsePythonUuid(text: string): string | undefined {
  requireString(text, "uuid text");

  // `replaceAll` matches Python's `str.replace`: all non-overlapping
  // occurrences, scanned left to right, with no re-scan of the replacement.
  // Both needles are ASCII, so neither can split a surrogate pair.
  const stripped = stripBraces(text.replaceAll("urn:", "").replaceAll("uuid:", "")).replaceAll(
    "-",
    "",
  );

  const codePoints = Array.from(stripped, (character) => character.codePointAt(0) as number);
  if (codePoints.length !== 32) {
    return undefined;
  }

  const value = pythonHexIntegerLiteral(transformDecimalAndSpaceToAscii(codePoints));
  if (value === undefined) {
    return undefined;
  }

  // CPython also checks `0 <= int < 1<<128` here. It is unreachable through
  // this path and so is deliberately not transcribed: the sign cannot be
  // negative (see above), and 32 characters cannot encode more than 32 hex
  // digits, which is exactly 2**128 - 1.
  return formatUuid(value);
}

/**
 * `uuid.uuid5(namespace, name)`, rendered as `str(...)` renders it.
 *
 * `namespace` is taken as a canonical UUID string rather than as an opaque
 * value: the only two namespaces in this belt are the constants above, and a
 * string keeps the module free of a UUID class that would exist solely to be
 * passed here. It is validated strictly -- *not* through
 * {@link parsePythonUuid} -- because a namespace is this port's own datum, not
 * a caller's id, and accepting `{...}` or a `urn:` prefix for it would be a
 * generalisation with no counterpart in the source.
 *
 * **The one deliberate narrowing in this module.** Python's
 * `bytes(name, "utf-8")` raises `UnicodeEncodeError` on a lone surrogate, so
 * interlock fails loudly. A JavaScript string can hold one, and both
 * `Buffer.from(s, "utf8")` and `TextEncoder` replace it with `U+FFFD` -- which
 * would map `"\ud800"`, `"\udc00"` and a literal `U+FFFD` to the **same** UUID. Three
 * distinct session ids sharing one CLI identity is a failure this function's
 * purity contract exists to prevent, and it is a failure interlock cannot have.
 * So a lone surrogate is refused here rather than silently folded. This is the
 * only input for which continuo throws where interlock throws a different
 * exception type, and it is recorded as a deviation rather than left to be
 * discovered.
 */
export function uuid5(namespace: string, name: string): string {
  requireString(namespace, "namespace");
  requireString(name, "name");
  if (!CANONICAL_UUID.test(namespace)) {
    throw new TypeError(
      `namespace must be a canonical lowercase UUID, got ${JSON.stringify(namespace)}`,
    );
  }

  const namespaceBytes = Buffer.from(namespace.replaceAll("-", ""), "hex");
  const digest = createHash("sha1")
    .update(Buffer.concat([namespaceBytes, encodeUtf8Strict(name)]))
    .digest();

  // `int.from_bytes(hash[:16])` -- big endian, which is `toString("hex")`.
  let value = BigInt(`0x${digest.subarray(0, 16).toString("hex")}`);
  // The four lines below are CPython's, verbatim. `bigint` bitwise operators
  // are two's complement over an unbounded width, so `~(0xc000n << 48n)` masks
  // exactly the two variant bits and nothing above them, as Python's does.
  value &= ~(0xc000n << 48n);
  value |= 0x8000n << 48n;
  value &= ~(0xf000n << 64n);
  value |= 5n << 76n;
  return formatUuid(value);
}

// --------------------------------------------------------------------------
// CPython's integer literal grammar, for base 16
// --------------------------------------------------------------------------

/**
 * `int(text, 16)`, restricted to what can reach it from {@link parsePythonUuid}.
 *
 * `int()` accepts a **literal**, not a digit run, and every part of that
 * literal fits inside the 32-character budget `uuid.UUID` imposes. All five
 * were measured accepted on 3.12.3, and each one changes the answer of
 * `claude_session_uuid` for an id a caller could plausibly choose -- the first
 * three are spellable in the `[A-Za-z0-9._-]` alphabet a session id needs
 * anyway in order to name a state directory:
 *
 * | input (32 chars)                   | CPython |
 * |------------------------------------|---------|
 * | `1_234567890abcdef1234567890abcde` | parses (underscores separate digits) |
 * | `0x34567890abcdef1234567890abcde1` | parses (base-16 prefix) |
 * | `+1234567890abcdef1234567890abcde` | parses (leading sign) |
 * | `\t1234567890abcdef1234567890abcde` | parses (surrounding whitespace) |
 * | `U+3000` + 31 hex digits           | parses (Unicode whitespace) |
 *
 * The grammar, as `long_from_string` implements it (whitespace already folded
 * to ASCII spaces by {@link transformDecimalAndSpaceToAscii}):
 *
 * ```
 * literal := WS* '+'? ( '0x' | '0X' ) '_'? DIGITS WS*
 *          | WS* '+'? DIGITS WS*
 * DIGITS  := hexdigit ( '_'? hexdigit )*
 * ```
 *
 * The underscore rule is the fiddly one and is easy to get one notch too
 * permissive: `0x_1` parses but `_1` does not, `1_2` parses but `1__2` and
 * `1_` do not. A leading `-` is not in the grammar above because
 * {@link parsePythonUuid} has already removed every `-` in the string; see its
 * documentation.
 */
function pythonHexIntegerLiteral(text: string): bigint | undefined {
  let start = 0;
  let end = text.length;
  while (start < end && isAsciiSpace(text[start] as string)) {
    start += 1;
  }
  while (end > start && isAsciiSpace(text[end - 1] as string)) {
    end -= 1;
  }

  if (start < end && text[start] === "+") {
    start += 1;
  }

  let prefixed = false;
  if (
    end - start >= 2 &&
    text[start] === "0" &&
    (text[start + 1] === "x" || text[start + 1] === "X")
  ) {
    start += 2;
    prefixed = true;
  }
  if (prefixed && start < end && text[start] === "_") {
    start += 1;
  }

  if (start >= end || !isHexDigit(text[start] as string)) {
    return undefined;
  }
  let digits = text[start] as string;
  start += 1;

  while (start < end) {
    if (text[start] === "_") {
      start += 1;
    }
    if (start >= end || !isHexDigit(text[start] as string)) {
      return undefined;
    }
    digits += text[start] as string;
    start += 1;
  }

  return BigInt(`0x${digits}`);
}

/**
 * `_PyUnicode_TransformDecimalAndSpaceToASCII`, the step `int()` runs before it
 * parses anything.
 *
 * Every code point below `127` is kept; Unicode whitespace becomes an ASCII
 * space; a Unicode decimal digit becomes the ASCII digit of the same value; and
 * anything else becomes `?`, which no later branch accepts. Transcribing it --
 * rather than treating "hex digits" as `[0-9a-fA-F]` -- is what makes
 * `U+3000` (ideographic space) and `U+0660` (Arabic-Indic zero) behave here
 * as they behave in interlock. The `< 127` boundary is CPython's own and puts
 * `U+007F` in the `?` branch.
 */
function transformDecimalAndSpaceToAscii(codePoints: readonly number[]): string {
  let out = "";
  for (const codePoint of codePoints) {
    if (codePoint < 127) {
      out += String.fromCodePoint(codePoint);
    } else if (INT_WHITESPACE.has(codePoint)) {
      out += " ";
    } else {
      const decimal = decimalDigitValue(codePoint);
      out += decimal < 0 ? "?" : String(decimal);
    }
  }
  return out;
}

/**
 * `Py_UNICODE_TODECIMAL`: the value of a Unicode decimal digit, or `-1`.
 *
 * Backed by the 68 block starts of general category `Nd`, enumerated from
 * `unicodedata` on the interpreter this module was measured against (Unicode
 * 15.0.0, shipped with Python 3.12.3). Every `Nd` block is exactly ten
 * consecutive code points whose values run `0..9`, which the generator
 * asserted; four blocks are adjacent to another (`U+1D7D8` and its
 * neighbours), which is why the base has to be looked up rather than found by
 * scanning backwards from the character.
 *
 * The table is pinned to *Python's* Unicode version on purpose, not to Node's:
 * Python is the oracle this port is checked against, and `\p{Nd}` in a
 * JavaScript regular expression answers from whatever ICU the runtime was
 * built with.
 */
function decimalDigitValue(codePoint: number): number {
  let low = 0;
  let high = DECIMAL_BLOCK_STARTS.length - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    const base = DECIMAL_BLOCK_STARTS[middle] as number;
    if (codePoint < base) {
      high = middle - 1;
    } else if (codePoint > base + 9) {
      low = middle + 1;
    } else {
      return codePoint - base;
    }
  }
  return -1;
}

