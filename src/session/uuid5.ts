/**
 * `claude_session_uuid`, and the exact slice of Python's `uuid` module it needs.
 *
 * Interlock derives the `--session-id` it hands `claude` from the caller's S1
 * session id, as a **pure function of the id alone**:
 *
 * ```python
 * def claude_session_uuid(session_id: str) -> str:
 *     try:
 *         return str(uuid.UUID(session_id))
 *     except ValueError:
 *         return str(uuid.uuid5(SESSION_UUID_NAMESPACE, session_id))
 * ```
 *
 * Purity is the whole point of the design, not a stylistic preference: the
 * binding row is committed *before* the spawn, and a supervisor restarted with
 * nothing but the id has to arrive at the same UUID without asking a process
 * that may no longer exist. That makes cross-runtime agreement a correctness
 * property of this port rather than a nicety. If continuo derives a different
 * UUID than interlock for any id, the two disagree about which CLI session a
 * row names -- silently, because both answers are well-formed UUIDs.
 *
 * So this module is written as a **transcription of CPython**, not as "a UUIDv5
 * helper". Three things are transcribed, and each of them is a place a
 * reasonable JavaScript implementation diverges:
 *
 * 1. **RFC 4122 v5 itself** -- SHA-1 over `namespace.bytes + name.encode()`,
 *    the first 16 bytes taken big-endian, then the variant and version bits
 *    overwritten. The bit surgery runs on a `bigint`, because a `number`
 *    cannot hold 128 bits (this is rule 9's "which `number` parameters does the
 *    source type as `int`" question, answered: the only integer here is the
 *    128-bit value, and it is a `bigint` end to end).
 * 2. **`uuid.UUID(...)`'s leniency.** Python accepts far more than the
 *    canonical `8-4-4-4-12` spelling, and every accepted spelling is *honoured
 *    verbatim* rather than hashed -- so a port that rejects a spelling Python
 *    accepts does not merely refuse, it silently returns a **different UUID**.
 *    See {@link parsePythonUuid}.
 * 3. **`str(uuid.UUID(...))`'s canonicalisation** -- lowercase hex, canonical
 *    dash positions, and *no* normalisation of the version or variant nibbles.
 *    `uuid.UUID("ffffffffffffffffffffffffffffffff")` is not a v5 and is
 *    printed unchanged; a helper that "fixes" the version bits on parse would
 *    corrupt an id a caller chose deliberately.
 *
 * The one place this module is deliberately **narrower** than CPython is a
 * lone UTF-16 surrogate; see {@link uuid5}. Everything else was measured
 * against `python3` 3.12.3 rather than reasoned about, and the measurements are
 * pinned by `test/session/uuid5.test.ts` against literals generated by that
 * interpreter -- not by this implementation, which would prove nothing.
 *
 * Ported from interlock `src/claude_org_runtime/session/claude_cli_provider.py`
 * at `65f36c5` (`SESSION_UUID_NAMESPACE`, `claude_session_uuid`), plus
 * CPython 3.12's `Lib/uuid.py` and `Objects/longobject.c`. Nothing here spawns,
 * reads the clock or touches the filesystem, so nothing here goes through the
 * belt's runtime seam.
 *
 * @internal Not package API (D-0101). Never re-exported from `src/index.ts`.
 */

import { Buffer } from "node:buffer";
import { createHash } from "node:crypto";

// --------------------------------------------------------------------------
// Tables measured out of CPython
//
// These sit above the namespace constant below because that constant is
// computed at module load and reaches `CANONICAL_UUID`: a `const` declared
// later in the file is in its temporal dead zone at that moment, and the
// module would fail to load with a `ReferenceError`.
// --------------------------------------------------------------------------

/** Strict `8-4-4-4-12`, lowercase. Only ever applied to a namespace. */
const CANONICAL_UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/**
 * `Py_UNICODE_ISSPACE`, as `int()` sees it -- twenty-five code points,
 * enumerated by testing every code point in `range(0x110000)` on 3.12.3.
 *
 * It is **not** `str.isspace()`: `U+001C` through `U+001F` are whitespace to
 * `str.isspace` and are *not* stripped by `int()`, so a table derived from the
 * more obvious predicate would accept four inputs CPython refuses.
 */
const INT_WHITESPACE = new Set([
  0x0009, 0x000a, 0x000b, 0x000c, 0x000d, 0x0020, 0x0085, 0x00a0, 0x1680, 0x2000, 0x2001, 0x2002,
  0x2003, 0x2004, 0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200a, 0x2028, 0x2029, 0x202f, 0x205f,
  0x3000,
]);

/** The 68 `Nd` block bases. See {@link decimalDigitValue}. Ascending. */
const DECIMAL_BLOCK_STARTS = [
  0x00030, 0x00660, 0x006f0, 0x007c0, 0x00966, 0x009e6, 0x00a66, 0x00ae6, 0x00b66, 0x00be6, 0x00c66,
  0x00ce6, 0x00d66, 0x00de6, 0x00e50, 0x00ed0, 0x00f20, 0x01040, 0x01090, 0x017e0, 0x01810, 0x01946,
  0x019d0, 0x01a80, 0x01a90, 0x01b50, 0x01bb0, 0x01c40, 0x01c50, 0x0a620, 0x0a8d0, 0x0a900, 0x0a9d0,
  0x0a9f0, 0x0aa50, 0x0abf0, 0x0ff10, 0x104a0, 0x10d30, 0x11066, 0x110f0, 0x11136, 0x111d0, 0x112f0,
  0x11450, 0x114d0, 0x11650, 0x116c0, 0x11730, 0x118e0, 0x11950, 0x11c50, 0x11d50, 0x11da0, 0x11f50,
  0x16a60, 0x16ac0, 0x16b50, 0x1d7ce, 0x1d7d8, 0x1d7e2, 0x1d7ec, 0x1d7f6, 0x1e140, 0x1e2f0, 0x1e4f0,
  0x1e950, 0x1fbf0,
];

