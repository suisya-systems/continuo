/** `'%032x' % value` split `8-4-4-4-12`, which is all `UUID.__str__` does. */
function formatUuid(value: bigint): string {
  const hex = value.toString(16).padStart(32, "0");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/**
 * `str.strip('{}')`: remove every leading and trailing `{` or `}`, in any
 * order and any number, and nothing from the middle.
 *
 * Indexing by UTF-16 code unit is safe here only because both characters are
 * ASCII, so neither can be half of a surrogate pair.
 */
function stripBraces(text: string): string {
  let start = 0;
  let end = text.length;
  while (start < end && (text[start] === "{" || text[start] === "}")) {
    start += 1;
  }
  while (end > start && (text[end - 1] === "{" || text[end - 1] === "}")) {
    end -= 1;
  }
  return text.slice(start, end);
}

/**
 * `bytes(name, "utf-8")`, which refuses a lone surrogate instead of replacing
 * it. See {@link uuid5} for why replacement is not an option here.
 */
function encodeUtf8Strict(name: string): Buffer {
  for (let index = 0; index < name.length; index += 1) {
    const unit = name.charCodeAt(index);
    if (unit >= 0xdc00 && unit <= 0xdfff) {
      throw new TypeError(`name contains a lone low surrogate at index ${index}`);
    }
    if (unit >= 0xd800 && unit <= 0xdbff) {
      const next = name.charCodeAt(index + 1);
      // `charCodeAt` past the end is NaN, and NaN fails both comparisons.
      if (!(next >= 0xdc00 && next <= 0xdfff)) {
        throw new TypeError(`name contains a lone high surrogate at index ${index}`);
      }
      index += 1;
    }
  }
  return Buffer.from(name, "utf8");
}

/**
 * The runtime half of a `string` parameter (rule 9).
 *
 * The message names the `typeof` and never the value: a rejected argument can
 * be anything at all, and this module's output has to stay ASCII (D-0006).
 */
function requireString(value: string, what: string): void {
  if (typeof value !== "string") {
    throw new TypeError(`${what} must be a string, got ${typeof value}`);
  }
}

function isAsciiSpace(character: string): boolean {
  return (
    character === " " ||
    character === "\t" ||
    character === "\n" ||
    character === "\v" ||
    character === "\f" ||
    character === "\r"
  );
}

function isHexDigit(character: string): boolean {
  return (
    (character >= "0" && character <= "9") ||
    (character >= "a" && character <= "f") ||
    (character >= "A" && character <= "F")
  );
}
