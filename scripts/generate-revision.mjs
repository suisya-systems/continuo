/**
 * Bake the build's git revision into the build output.
 *
 * `tsc` emits `dist/build_revision.js` from the committed placeholder in
 * `src/build_revision.ts`, which says `unknown`. This step runs after it and
 * overwrites the emitted module with the same module carrying the real
 * revision. Nothing under `src/` is touched, so a build never dirties the
 * working tree it was produced from -- which matters here more than usual,
 * because a build that dirtied its own tree would make the NEXT build report
 * `-dirty` for no reason.
 *
 * Shaped like `copy-migrations.mjs`, and for the same reasons: paths derived
 * from this script's own URL rather than from the working directory; the rule
 * IMPORTED from the build output rather than restated here, so the packaging
 * rule cannot drift from the rule the runtime believes; and what was written is
 * verified by reading it back, because a generator nobody checks is a generator
 * that eventually writes nothing.
 *
 * **Validated before it is written, not after.** An unvalidated string
 * interpolated into `export const BUILD_REVISION = "..."` is arbitrary
 * JavaScript in a shipped module. `REVISION_PATTERN` is checked first, which
 * also keeps the generated bytes ASCII -- `test/contract/ascii-output-policy.test.ts`
 * skips `dist/`, so this check is what upholds `docs/cli-output-policy.md` for
 * these bytes.
 *
 * **Fails open by default and closed on request.** A missing revision only
 * makes a build less identifiable; it does not break it, and a contributor
 * building on a machine with no git must not be stopped. So an underivable
 * revision is written as `unknown` with an explanatory line on stderr. That is
 * the wrong trade for exactly one path -- a release -- so
 * `CONTINUO_REQUIRE_REVISION=1` turns the same condition into a failure, and the
 * publish path sets it. This deliberately differs from the `copy-*` steps,
 * which fail closed unconditionally: a missing migration ledger makes every
 * opener refuse a database, which is a different order of harm.
 *
 * **ASCII only**, per `docs/cli-output-policy.md`: this runs during
 * `npm run build` on the required windows-latest cell.
 */

import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

import { ascii, readGitRevision } from "./lib/build-revision.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MODULE = join(ROOT, "dist", "build_revision.js");
const SOURCEMAP = `${MODULE}.map`;

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

// Imported from dist rather than re-declared, exactly as copy-migrations.mjs
// imports STEP_FILENAME: a second copy of the alphabet is a second thing to
// keep in sync, and the one that matters is the one the runtime believes.
//
// `pathToFileURL`, never the bare path: on Windows an absolute path starts with
// a drive letter, which the ESM loader reads as a URL scheme and rejects
// (ERR_UNSUPPORTED_ESM_URL_SCHEME, "Received protocol 'd:'"). On POSIX the bare
// path happens to resolve, so this is invisible everywhere except the cell that
// catches it.
const { REVISION_PATTERN, REVISION_UNKNOWN } = await import(
  pathToFileURL(join(ROOT, "dist", "about.js")).href
);

// A build that skipped `tsc` would otherwise get a generated module beside no
// compiled CLI, and would fail later with something that does not name the
// cause.
try {
  readFileSync(join(ROOT, "dist", "cli.js"));
} catch {
  // The path is escaped for the reason `explain` escapes its own: ROOT comes
  // from wherever the package was checked out, and every byte this step writes
  // is covered by docs/cli-output-policy.md.
  fail(
    `${ascii(join(ROOT, "dist", "cli.js"))} is missing, so tsc has not run. ` +
      "This step rewrites what tsc emitted; it cannot run first.",
  );
}

const { revision, why } = readGitRevision(ROOT);

if (!REVISION_PATTERN.test(revision)) {
  fail(
    `derived revision ${JSON.stringify(revision)} is not one this build may ship. ` +
      "A revision is 40 hex digits, optionally followed by -dirty, or the literal " +
      `${REVISION_UNKNOWN}; anything else would be written verbatim into a JavaScript module.`,
  );
}

if (revision === REVISION_UNKNOWN) {
  const detail = why === "" ? "no reason recorded" : why;
  if (process.env.CONTINUO_REQUIRE_REVISION === "1") {
    fail(
      `revision: could not derive a git revision (${detail}), and ` +
        "CONTINUO_REQUIRE_REVISION=1 forbids shipping a build that does not know which " +
        "commit produced it.",
    );
  }
  // Visible in the build log rather than silent: a publish from a tree with no
  // repository is the case this warning exists to make noticeable.
  process.stderr.write(`revision: unknown (${detail})\n`);
}

writeFileSync(MODULE, `export const BUILD_REVISION = ${JSON.stringify(revision)};\n`, "utf8");

// tsc's sourcemap for this module now points at bytes that are gone. Removing
// it is cheaper and more honest than correcting it for a one-line module.
rmSync(SOURCEMAP, { force: true });

// Verify what landed, through the module system rather than by re-reading the
// text: what matters is the value an importer sees, which is what `dist/cli.js`
// will import.
const written = await import(`${pathToFileURL(MODULE).href}?generated=${revision}`);
if (written.BUILD_REVISION !== revision) {
  fail(
    `${ascii(MODULE)} exports ${ascii(JSON.stringify(written.BUILD_REVISION))} after being ` +
      `written with ${JSON.stringify(revision)}`,
  );
}

process.stdout.write(`revision: ${revision} -> dist/build_revision.js\n`);
